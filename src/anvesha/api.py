"""Authenticated, durable search-job HTTP API (ANV-004)."""

import hashlib
import json
import secrets
from contextlib import asynccontextmanager
from importlib.resources import files
from typing import Annotated, Literal

from fastapi import Depends, FastAPI, Header, HTTPException, Query, Request, Response
from fastapi.responses import HTMLResponse
from fastapi.security import APIKeyHeader
from pydantic import BaseModel, ConfigDict, Field, StrictBool, StrictInt, field_validator

from anvesha import __version__
from anvesha.config import Settings
from anvesha.store import FeedbackError, IdempotencyConflict, Store


class SearchRequest(BaseModel):
    model_config = ConfigDict(extra="forbid")
    query: str = Field(min_length=1, max_length=2000)
    sources: list[Literal["local", "wikidata"]] = Field(
        default_factory=lambda: ["local"], min_length=1, max_length=2
    )
    limit: StrictInt = Field(default=10, ge=1, le=50)
    ranking: Literal["lexical", "llm"] = "llm"

    @field_validator("query")
    @classmethod
    def meaningful_query(cls, value):
        value = value.strip()
        if not value:
            raise ValueError("Query must not be blank")
        return value

    @field_validator("sources")
    @classmethod
    def canonical_sources(cls, value):
        return sorted(set(value))


class FeedbackRequest(BaseModel):
    model_config = ConfigDict(extra="forbid")
    version: StrictInt = Field(ge=1)
    result_id: str | None = Field(default=None, min_length=1, max_length=128)
    rating: StrictInt
    reason: (
        Literal[
            "relevant",
            "irrelevant",
            "outdated",
            "incorrect",
            "wrong_locale",
            "duplicate",
            "inaccessible",
            "promotional",
            "missing_information",
        ]
        | None
    ) = None
    comment: str | None = Field(default=None, max_length=2000)
    learning_opt_in: StrictBool = False

    @field_validator("rating")
    @classmethod
    def valid_rating(cls, value):
        if value not in (-1, 1):
            raise ValueError("Rating must be -1 or 1")
        return value


def public_job(job):
    fields = (
        "id",
        "query",
        "sources",
        "limit",
        "state",
        "phase",
        "attempts",
        "results_version",
        "warnings",
        "error_code",
        "created_at",
        "updated_at",
        "pipeline_version",
        "ranking",
    )
    result = {key: job[key] for key in fields if key in job}
    active = job["state"] in {"queued", "running"}
    result.update(
        next_poll_after_ms=1000 if active else None,
        results_available=job["results_version"] > 0,
        results_url=f"/v1/searches/{job['id']}/results",
        coverage="configured_sources_only",
    )
    return result


def create_app(settings: Settings | None = None) -> FastAPI:
    settings = settings or Settings.from_env()
    store = Store(settings.database_path)

    @asynccontextmanager
    async def lifespan(app):
        if not settings.api_keys:
            raise RuntimeError("Set ANVESHA_API_KEYS using a key generated by 'anvesha init'")
        store.initialize()
        yield

    app = FastAPI(
        title="Anvesha — Private Search for Your Own AI Tools",
        version=__version__,
        lifespan=lifespan,
        docs_url=None,
        redoc_url=None,
        description="Open-source search for user-controlled research, development and personal "
        "tools; local inference with no mandatory paid API or hosted model.",
    )
    app.state.store = store
    api_key_header = APIKeyHeader(name="X-API-Key", auto_error=False)

    def require_owner(key: str | None = Depends(api_key_header)):
        supplied = (key or "").encode("utf-8")
        matches = [secrets.compare_digest(supplied, item.encode()) for item in settings.api_keys]
        if not key or not any(matches):
            raise HTTPException(401, "invalid_api_key")
        return hashlib.sha256(supplied).hexdigest()

    def owned_job(owner, job_id):
        job = store.get_job(owner, job_id)
        if job is None:
            raise HTTPException(404, "search_not_found")
        return job

    @app.middleware("http")
    async def private_responses(request: Request, call_next):
        response = await call_next(request)
        response.headers["Cache-Control"] = "no-store"
        response.headers["X-Content-Type-Options"] = "nosniff"
        response.headers["Referrer-Policy"] = "no-referrer"
        response.headers["X-DNS-Prefetch-Control"] = "off"
        response.headers["Content-Security-Policy"] = (
            "default-src 'none'; script-src 'self'; style-src 'self'; "
            "connect-src 'self'; img-src 'self'; base-uri 'none'; "
            "form-action 'self'; frame-ancestors 'none'; object-src 'none'"
        )
        return response

    @app.get("/", response_class=HTMLResponse, include_in_schema=False)
    def browser_ui():
        return files("anvesha").joinpath("web/index.html").read_text(encoding="utf-8")

    @app.get("/assets/{name}", include_in_schema=False)
    def browser_asset(name: str):
        media = {"app.js": "application/javascript", "styles.css": "text/css"}
        if name not in media:
            raise HTTPException(404, "asset_not_found")
        return Response(files("anvesha").joinpath("web", name).read_bytes(), media_type=media[name])

    @app.get("/healthz")
    def health():
        return {"status": "ok", "version": __version__}

    @app.get("/v1/capabilities")
    def capabilities(owner: str = Depends(require_owner)):
        return {
            "sources": list(settings.enabled_sources),
            "ranking_modes": ["llm", "lexical"] if settings.llm.enabled else ["lexical"],
            "default_ranking": "llm",
            "llm_configured": settings.llm.enabled,
            "document_count": store.document_count(),
            "llm_source_scope": ["local"],
            "llm_endpoint_scope": settings.llm.endpoint_scope if settings.llm.enabled else None,
            "gateway_downstream_verified": False,
            "coverage": "configured_sources_only",
        }

    @app.post("/v1/searches", status_code=202)
    def create_search(
        body: SearchRequest,
        response: Response,
        owner: str = Depends(require_owner),
        idempotency_key: Annotated[str | None, Header(min_length=1, max_length=128)] = None,
    ):
        if set(body.sources) - set(settings.enabled_sources):
            raise HTTPException(422, "source_not_enabled")
        if body.ranking == "llm":
            if not settings.llm.enabled:
                raise HTTPException(422, "llm_not_configured")
            if body.sources != ["local"]:
                raise HTTPException(422, "llm_local_source_only")
        if idempotency_key is not None and not idempotency_key.strip():
            raise HTTPException(422, "invalid_idempotency_key")
        try:
            job, created = store.create_search(
                owner,
                body.query,
                body.sources,
                body.limit,
                idempotency_key,
                ranking=body.ranking,
                pipeline_version=settings.llm.pipeline_version if body.ranking == "llm" else None,
            )
        except IdempotencyConflict as exc:
            raise HTTPException(409, "idempotency_key_conflict") from exc
        response.status_code = 202 if created else 200
        response.headers["Location"] = f"/v1/searches/{job['id']}"
        response.headers["Retry-After"] = "1"
        response.headers["Idempotency-Replayed"] = str(not created).lower()
        return public_job(job)

    @app.get("/v1/searches/{job_id}")
    def get_search(
        job_id: str,
        request: Request,
        response: Response,
        owner: str = Depends(require_owner),
    ):
        payload = public_job(owned_job(owner, job_id))
        etag = '"' + hashlib.sha256(json.dumps(payload, sort_keys=True).encode()).hexdigest() + '"'
        if request.headers.get("if-none-match") == etag:
            return Response(status_code=304, headers={"ETag": etag})
        response.headers["ETag"] = etag
        if payload["state"] in {"queued", "running"}:
            response.headers["Retry-After"] = "1"
        return payload

    @app.get("/v1/searches/{job_id}/results")
    def get_results(
        job_id: str,
        version: Annotated[int | None, Query(ge=1)] = None,
        offset: Annotated[int, Query(ge=0)] = 0,
        limit: Annotated[int, Query(ge=1, le=50)] = 10,
        owner: str = Depends(require_owner),
    ):
        job = owned_job(owner, job_id)
        try:
            snapshot = store.get_results(owner, job_id, version, offset, limit)
        except ValueError as exc:
            raise HTTPException(409, "result_version_unavailable") from exc
        if snapshot is None:
            raise HTTPException(404, "search_not_found")
        if snapshot["version"] == 0:
            raise HTTPException(409, "results_not_available")
        next_offset = offset + len(snapshot["results"])
        return {
            "search_id": job_id,
            **snapshot,
            "pipeline_version": job["pipeline_version"],
            "ranking": job["ranking"],
            "offset": offset,
            "next_offset": next_offset if next_offset < snapshot["total"] else None,
            "coverage": "configured_sources_only",
        }

    @app.post("/v1/searches/{job_id}/feedback")
    def feedback(job_id: str, body: FeedbackRequest, owner: str = Depends(require_owner)):
        owned_job(owner, job_id)
        try:
            saved = store.submit_feedback(owner, job_id, **body.model_dump())
        except FeedbackError as exc:
            raise HTTPException(409, "feedback_snapshot_or_result_invalid") from exc
        allowed = {
            "id",
            "job_id",
            "search_id",
            "version",
            "result_id",
            "rating",
            "reason",
            "comment",
            "learning_opt_in",
            "created_at",
            "updated_at",
            "pipeline_version",
        }
        return {key: value for key, value in saved.items() if key in allowed}

    @app.post("/v1/searches/{job_id}/cancel")
    def cancel(job_id: str, owner: str = Depends(require_owner)):
        job = store.cancel_job(owner, job_id)
        if job is None:
            raise HTTPException(404, "search_not_found")
        return public_job(job)

    @app.delete("/v1/searches/{job_id}", status_code=204)
    def delete(job_id: str, owner: str = Depends(require_owner)):
        if not store.delete_job(owner, job_id):
            raise HTTPException(404, "search_not_found")
        return Response(status_code=204)

    return app
